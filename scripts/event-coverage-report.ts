/**
 * Writes docs/EVENT_COVERAGE.md from content/events/inventory.draft.json, content/events/narrative-ranges.json and the
 * imported Quran text. The same numbers appear on /admin/events/coverage (which reads the database instead).
 *   pnpm tsx scripts/event-coverage-report.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { computeCoverage, refsText, rangesOf } from "../src/lib/events/coverage";
import type { Inventory } from "../src/lib/events/seed-sql";
import { TRACK_IDS } from "../src/lib/events/tracks";
import { ayahCounts, loadQuran, parseRef, type Ref } from "../src/lib/events/verify";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inv = JSON.parse(readFileSync(join(root, "content", "events", "inventory.draft.json"), "utf8")) as Inventory;
const nr = JSON.parse(readFileSync(join(root, "content", "events", "narrative-ranges.json"), "utf8")) as {
  toResearch: Array<{ ref: string; label: string; why: string }>;
  reviewedNotCounted: Array<{ ref: string; label: string; reason: string }>;
};
const q = loadQuran(root);
const counts = ayahCounts(q);
const refs = (list: string[]): Ref[] => list.map((r) => parseRef(r)!);

const invRefs = inv.items.flatMap((i) => refs(i.refs));
const cov = computeCoverage(invRefs, refs(nr.toResearch.map((r) => r.ref)));
const surahNames = JSON.parse(readFileSync(join(root, "content", "quran", "surahs.json"), "utf8")) as Array<{ number: number; name: string; english: string }>;
const sn = (n: number) => surahNames.find((s) => s.number === n)?.name ?? String(n);

const perTrack = TRACK_IDS.map((t) => {
  const items = inv.items.filter((i) => i.track === t);
  return { t, items, refs: items.reduce((s, i) => s + i.refs.length, 0), later: items.filter((i) => i.name_source === "later_tradition").length };
});

const lines: string[] = [];
const w = (s = "") => lines.push(s);
w("# Event Universe: research coverage");
w();
w("Generated by `pnpm tsx scripts/event-coverage-report.ts` from `content/events/inventory.draft.json`, `content/events/narrative-ranges.json` and the imported Quran text (Tanzil Uthmani). The same figures are shown, from the database, on `/admin/events/coverage`.");
w();
w("## How the inventory was built");
w();
w("1. The imported Arabic text (`content/quran/quran.txt`) was read surah by surah, with a word search to find where each prophet, person, community and event is named or described. The surah list and general knowledge were used only to find candidates.");
w("2. Every reference was then checked against the text itself: the range must exist, and it must contain a named anchor word for the item (a name or a distinctive term). Ranges whose anchor was missing were corrected or dropped. `tests/unit/events.test.ts` re-runs this check on every reference in the inventory and in the migration.");
w("3. Passages whose event or people are given only by later sources were not given an item; they are listed below as \"to research\".");
w("4. A last pass looked for runs of verses that open like a narrative (\"and when\", \"he said\", \"then when\") and are not covered. It found six runs: five were scenes of the Hereafter or statements of opposition (listed under \"reviewed, not counted\") and one (40:47-53) was the same scene running into the next story.");
w();
w("What this does **not** prove: that the register is complete. \"Narrative\" is an editorial judgement. The percentage below is the share of the *register* (the inventory plus the passages still to research) that an inventory item covers.");
w();
w("All 159 items are **drafts**. Nothing is public, dated or ordered: every item is in the \"Order not established\" lane until a reviewer adds a cited ordering claim. No year, Hijri or CE, is stored for any item.");
w();
w("## Numbers");
w();
w(`- Inventory items: **${inv.items.length}** (all draft)`);
w(`- Verse references: **${invRefs.length}**, covering **${cov.covered}** distinct ayat in **${new Set(invRefs.map((r) => r.surah)).size}** surahs`);
w(`- Narrative register: **${cov.narrative}** ayat; covered by an inventory item: **${cov.covered}** (**${cov.percent}%**); not yet covered: **${cov.uncovered}**`);
w(`- Items whose name is from later tradition (flagged \`name_source: later_tradition\`): **${inv.items.filter((i) => i.name_source === "later_tradition").length}**`);
w();
w("| Track | Items | Verse references | Later-tradition names |");
w("|---|---:|---:|---:|");
for (const p of perTrack) w(`| ${p.t} | ${p.items.length} | ${p.refs} | ${p.later} |`);
w(`| **Total** | **${inv.items.length}** | **${invRefs.length}** | **${inv.items.filter((i) => i.name_source === "later_tradition").length}** |`);
w();
w("## Ranges not yet covered (to research)");
w();
w("| Range | What it is | Why it has no item yet |");
w("|---|---|---|");
for (const r of nr.toResearch) w(`| ${r.ref} (${sn(parseRef(r.ref)!.surah)}) | ${r.label} | ${r.why} |`);
w();
w(`Uncovered ranges as the report computes them: ${refsText(cov.uncoveredRanges)}.`);
w();
w("## Reviewed and not counted");
w();
w("| Range | What it is | Why it is not counted |");
w("|---|---|---|");
for (const r of nr.reviewedNotCounted) w(`| ${r.ref} (${sn(parseRef(r.ref)!.surah)}) | ${r.label} | ${r.reason} |`);
w();
w("## Identification and naming flags");
w();
w("These items carry `name_source: later_tradition`: a name used for the item is not in the cited passage (the tests check that the name does not occur in the text where that can be checked). The tradition behind the name is to be added as a separate, cited, disputed claim (`event_identifications`); it is never part of the item.");
w();
for (const i of inv.items.filter((x) => x.name_source === "later_tradition")) w(`- **${i.title}** (${i.track}): ${i.refs.join(", ")}`);
w();
w("Other cases that need an identification claim before they are published, because the passage does not state them:");
w();
w("- **Ibrahim's son in the vision of the sacrifice** (37:99-113): the passage says \"a forbearing boy\" and does not name him; which son it was is disputed among scholars. The item is titled without a name.");
w("- **Dhul-Qarnayn** (18:83-98), **the People of the Cave** (18:9-26), **the servant with Musa** (18:60-82): who or when they were is not in the text.");
w("- **The Queen of Saba** (27:22-44): the passage says \"a woman ruling them\"; the name Bilqis is later tradition and is not used.");
w("- **Uhud, Hudaybiyyah, Tabuk, Banu al-Nadir, the Trench**: the passages describe the events but do not use these names.");
w("- **Companions of the Town** (36:13-29) and **the two owners of gardens** (18:32-44) are introduced by the text itself as examples (\"set forth for them a parable\"), so they sit in the Parables track and are never dated.");
w();
w("## Inventory by track");
w();
for (const p of perTrack) {
  w(`### ${p.t} (${p.items.length})`);
  w();
  for (const i of p.items) w(`- \`${i.slug}\` ${i.title}${i.name_source === "later_tradition" ? " *(name from later tradition)*" : ""}: ${i.refs.join(", ")}`);
  w();
}
w("## Covered ayat by surah");
w();
w("| Surah | Narrative ayat | Covered |");
w("|---|---:|---:|");
for (const s of cov.bySurah) w(`| ${s.surah} ${sn(s.surah)} | ${s.narrative} of ${counts[s.surah]} | ${s.covered} |`);
w();
w(`Covered ranges: ${refsText(rangesOf(invRefs.flatMap((r) => Array.from({ length: r.to - r.from + 1 }, (_, k) => `${r.surah}:${r.from + k}`))))}.`);
w();
writeFileSync(join(root, "docs", "EVENT_COVERAGE.md"), lines.join("\n"));
console.log(`docs/EVENT_COVERAGE.md written: ${inv.items.length} items, ${cov.percent}% of the register covered.`);
