/**
 * Generates src/styles/tokens.css and src/styles/tokens.generated.ts from design/tokens/tokens.json.
 * The JSON is the single source of truth; never hand-edit the outputs. Run: pnpm tokens
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

type Themed = string | Record<string, string>;
interface Tok { name: string; value: Themed }
interface TypeStyle { name: string; family?: string; fontSize: string; lineHeight: string; fontWeight: number; letterSpacing?: string }
interface Tokens {
  color: { themes: { id: string }[]; tokens: Tok[] };
  type: { families: Record<string, string>; groups: { family: string; styles: TypeStyle[] }[] };
  spacing: { tokens: Tok[] };
  radius: { tokens: Tok[] };
  shadow: { tokens: Tok[] };
  breakpoint: { tokens: Tok[] };
  size: { tokens: Tok[] };
  zIndex: { tokens: Tok[] };
}

/** next/font exposes self-hosted faces as --ff-* variables; the literal family names stay as fallbacks. */
const FAMILY_VARS: Record<string, string> = {
  display: 'var(--ff-serif, "Source Serif 4"), var(--ff-naskh, "Noto Naskh Arabic"), Georgia, serif',
  sans: 'var(--ff-plex, "IBM Plex Sans"), var(--ff-plex-ar, "IBM Plex Sans Arabic"), system-ui, sans-serif',
  quran: 'var(--ff-amiri-quran, "Amiri Quran"), var(--ff-amiri, "Amiri"), var(--ff-naskh, "Noto Naskh Arabic"), serif',
  naskh: 'var(--ff-naskh, "Noto Naskh Arabic"), var(--ff-amiri, "Amiri"), serif',
  mono: 'var(--ff-mono, "IBM Plex Mono"), ui-monospace, monospace',
};

export function loadTokens(path = resolve(root, "design/tokens/tokens.json")): Tokens {
  return JSON.parse(readFileSync(path, "utf8")) as Tokens;
}

const ref = (v: string) => v.replace(/^\{(.+)\}$/, "var(--$1)");

function themeValue(t: Tok, theme: string): string {
  if (typeof t.value === "string") return ref(t.value);
  const v = t.value[theme];
  if (v == null) throw new Error(`token ${t.name} has no value for theme ${theme}`);
  return ref(v);
}

export function buildCss(tokens: Tokens): string {
  const themes = tokens.color.themes.map((t) => t.id);
  const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
  const blocks = themes.map((theme) => {
    // A page that owns the journey theme also themes <html>, so the scrollbar gutter and overscroll match it.
    const sel =
      theme === "light"
        ? ':root, [data-theme="light"]'
        : theme === "journey"
          ? '[data-theme="journey"], html:has(> body > [data-theme="journey"])'
          : `[data-theme="${theme}"]`;
    const body = themed.map((t) => `  --${t.name}: ${themeValue(t, theme)};`).join("\n");
    const scheme = theme === "light" ? "" : "\n  color-scheme: dark;";
    return `${sel} {\n${body}${scheme}\n}`;
  });
  // With no explicit choice, follow the system preference.
  if (themes.includes("dark")) {
    const body = themed.map((t) => `    --${t.name}: ${themeValue(t, "dark")};`).join("\n");
    blocks.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${body}\n  }\n}`);
  }
  const flat = [...tokens.spacing.tokens, ...tokens.radius.tokens, ...tokens.breakpoint.tokens, ...tokens.size.tokens, ...tokens.zIndex.tokens];
  const families = Object.keys(tokens.type.families).map((k) => `  --font-${k}: ${FAMILY_VARS[k] ?? tokens.type.families[k]};`);
  const statics = `:root {\n${flat.map((t) => `  --${t.name}: ${t.value as string};`).join("\n")}\n${families.join("\n")}\n}`;
  const typeClasses = tokens.type.groups.flatMap((g) =>
    g.styles.map((s) => {
      const fam = s.family ?? g.family;
      const ls = s.letterSpacing ? ` letter-spacing: ${s.letterSpacing};` : "";
      return `.type-${s.name} { font: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${fam});${ls} }`;
    }),
  );
  return [
    "/* ZIQ tokens: generated by scripts/build-tokens.ts from design/tokens/tokens.json. Do not edit by hand. */",
    ...blocks,
    statics,
    ...typeClasses,
    "",
  ].join("\n\n");
}

export function buildTs(tokens: Tokens): string {
  const out = {
    colors: tokens.color.tokens.map((t) => t.name),
    shadows: tokens.shadow.tokens.map((t) => t.name),
    spacing: tokens.spacing.tokens.map((t) => t.name),
    radius: tokens.radius.tokens.map((t) => t.name),
    breakpoints: Object.fromEntries(tokens.breakpoint.tokens.map((t) => [t.name.replace(/^bp-/, ""), t.value as string])),
    zIndex: tokens.zIndex.tokens.map((t) => t.name),
    families: Object.keys(tokens.type.families),
    typeStyles: tokens.type.groups.flatMap((g) => g.styles.map((s) => s.name)),
  };
  return `// Generated by scripts/build-tokens.ts. Do not edit by hand.\nexport const TOKENS = ${JSON.stringify(out, null, 2)} as const;\n`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const t = loadTokens();
  writeFileSync(resolve(root, "src/styles/tokens.css"), buildCss(t));
  writeFileSync(resolve(root, "src/styles/tokens.generated.ts"), buildTs(t));
  console.log("tokens: wrote src/styles/tokens.css and src/styles/tokens.generated.ts");
}
