/**
 * Builds a reading pack per story draft for scholarly reviewers: docs/review-packs/<slug>.md.
 *
 *   pnpm review:packs            every draft present
 *   pnpm review:packs yusuf      one or more slugs
 *
 * Each pack lists, per chapter, the cited ayat (Tanzil Uthmani text, verbatim) next to every claim and the draft text with its
 * claim markers, then the review checklist of docs/STORY_DRAFTS.md. The pack changes no draft and states no verdict: it only puts the
 * source and the wording side by side. The Quran text is reproduced verbatim from content/quran (Tanzil Project, CC BY 3.0).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { StoryDraftSchema, formatRange, type DraftChapter, type VerseRange } from "../src/lib/stories/draft";
import { loadDraftFiles } from "../src/lib/stories/draft-load";
import { loadQuran } from "../src/lib/events/verify";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const only = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const quran = loadQuran(root);

function ayat(r: VerseRange): string {
  const out: string[] = [];
  for (let a = r.from; a <= r.to; a++) out.push(`> **${r.surah}:${a}** ${quran.get(`${r.surah}:${a}`) ?? "(not found)"}`);
  return out.join("\n>\n");
}

const MODES: Array<[keyof DraftChapter, string]> = [
  ["summary_md", "One-minute summary"],
  ["body_md", "Complete story"],
  ["deep_md", "Deep study"],
  ["kids_md", "Kids mode"],
  ["lessons_md", "Life lessons (educational interpretation)"],
  ["unknowns_md", "What the sources do not establish"],
];

const CHECKLIST = [
  "Verses: do the listed ayat really contain what each claim says? Is any claim stronger than its ayat?",
  "Pronouns and speakers: where the Arabic names none, does the draft say so?",
  "Words with more than one reading: decide how the page words each.",
  "Omissions: anything the verses say that readers need and the chapter leaves out?",
  "No added facts: no name, number, place, reason, emotion or sequence beyond the ayat; no implied chronology.",
  "No depiction of any prophet, angel or jinn.",
  "Theology and etiquette: cautious wording about prophets; no verdicts; no legal or medical ruling.",
  "Kids mode only restates the claims; nothing frightening or misleading.",
  "Lessons are marked as interpretation and are modest; none reads as scripture or a promise.",
  "Unknowns and tradition: each 'Named in later tradition' line is accurate and only a label.",
  "Titles and honorifics: bare names in the draft; honorifics added at render time.",
  "Sign-off goes in the platform review flow (name, version, decision), not in this file.",
];

mkdirSync(join(root, "docs", "review-packs"), { recursive: true });
for (const f of loadDraftFiles(root)) {
  if (only.length && !only.includes(f.slug)) continue;
  const parsed = StoryDraftSchema.safeParse(f.raw);
  if (!parsed.success) {
    console.log(`skip ${f.file}: does not parse (run pnpm check:drafts)`);
    continue;
  }
  const d = parsed.data;
  const L: string[] = [];
  L.push(`# Review pack: ${d.title_en}`, "");
  L.push("**Status: DRAFT, unreviewed, unpublished.** Generated from `content/stories/" + f.file + "`; do not edit this file (regenerate it).", "");
  L.push("Quran text: Tanzil Project (https://tanzil.net/), Uthmani 1.1, CC BY 3.0, reproduced verbatim. The English is the drafter's own wording of what the ayat state; it is not a translation of the Quran.", "");
  if (d.notes) L.push(`Notes from the drafter: ${d.notes}`, "");
  if (d.uncertainties_en?.length) {
    L.push("## Story-level uncertainties", "");
    for (const u of d.uncertainties_en) L.push(`- ${u}`);
    L.push("");
  }
  L.push("## How to review", "", ...CHECKLIST.map((c, i) => `${i + 1}. ${c}`), "");
  for (const ch of [...d.chapters].sort((a, b) => a.position - b.position)) {
    L.push(`---`, "", `## ${ch.position}. ${ch.title_en}  (\`#${ch.anchor}\`)`, "");
    L.push(`Cited ayat: ${ch.verses.map(formatRange).join(", ")}`, "");
    for (const r of ch.verses) L.push(ayat(r), "");
    L.push("### Claims", "");
    for (const c of ch.claims) {
      L.push(`**${c.id}** (${c.verses.map(formatRange).join(", ")}): ${c.statement_en}`, "");
    }
    for (const [key, label] of MODES) {
      const v = ch[key] as string | null | undefined;
      L.push(`### ${label}`, "", v && v.trim() ? v.trim() : "_empty_", "");
    }
    L.push("### Reviewer notes", "", "- [ ] chapter checked against the ayat", "- Notes:", "");
  }
  writeFileSync(join(root, "docs", "review-packs", `${d.slug}.md`), L.join("\n"), "utf8");
  console.log(`wrote docs/review-packs/${d.slug}.md (${d.chapters.length} chapters)`);
}
