/**
 * Builds the reviewer pack for the redesign's draft content: docs/review-packs/redesign-draft-atlas.md.
 *
 *   pnpm tsx scripts/build-redesign-review-pack.ts
 *
 * It covers the three draft files that stand in for the database when nothing is published (content/last-hour, content/lineage,
 * content/events/placement) and the Arabic and Urdu interface strings of the redesign views. Every cited ayah is reproduced
 * verbatim from content/quran (Tanzil Project, CC BY 3.0) next to the claim that cites it. The pack changes no draft and states no
 * verdict: it only puts the source and the wording side by side, with the questions a reviewer must answer.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { draftLastHour, draftLineage, draftTimeline } from "../src/content/draftAtlas";
import { redesignStrings } from "../src/lib/i18n/modules/redesign";
import { loadQuran } from "../src/lib/events/verify";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const quran = loadQuran(root);

/** "18:94–99" or "7:187" to verbatim ayat lines; anything else (a book, a hadith placeholder) is returned as a source to pin. */
function ayat(ref: string): string {
  const m = /^(\d{1,3}):(\d{1,3})(?:[–-](\d{1,3}))?$/.exec(ref.trim());
  if (!m) return `> **Source to pin:** ${ref}`;
  const s = Number(m[1]);
  const from = Number(m[2]);
  const to = m[3] ? Number(m[3]) : from;
  const out: string[] = [];
  for (let a = from; a <= to; a++) out.push(`> **${s}:${a}** ${quran.get(`${s}:${a}`) ?? "(not found in the imported text)"}`);
  return out.join("\n>\n");
}

function leaves(o: unknown, prefix = ""): Array<[string, string]> {
  if (typeof o === "string") return [[prefix, o]];
  if (typeof o !== "object" || o === null) return [];
  return Object.entries(o).flatMap(([k, v]) => leaves(v, prefix ? `${prefix}.${k}` : k));
}

const lines: string[] = [];
const push = (...s: string[]) => lines.push(...s);

push(
  "# Reviewer pack: the redesign's draft content",
  "",
  "Status: **draft, pending scholarly review.** Nothing here is approved. The pages that show this content carry a visible draft banner; they are",
  "replaced by reviewed database content as soon as any is published. Generated by `scripts/build-redesign-review-pack.ts`.",
  "",
  "How to review: for each entry decide Approve, Request changes (with a note) or Reject, and pin every `Source to pin` to a verified edition",
  "(book, edition, page or hadith number) before the entry can move out of draft. A hadith number reads `No. —` until it is pinned.",
  "",
);

/* ---------- Last Hour ---------- */
const lh = draftLastHour();
push("## 1. The Last Hour (`content/last-hour/signs.draft.json`)", "");
push(
  "Rules the page keeps: no date, no year, no countdown; the order among the signs is not stated; the Mahdi is left out until his grading and",
  "details are decided by the review board.",
  "",
  "Questions for every entry: (a) does the citation say what the title says? (b) is the evidence label right (Quran, authentic Hadith, scholarly",
  "interpretation, scholars differ)? (c) is the wording free of dates, places and current-events claims? (d) is the hadith source named and gradable?",
  "",
);
for (const s of lh.signs) {
  push(`### ${s.title}${s.major ? " (major sign)" : ""}`, "");
  push(`- Evidence labels: ${s.evidence.join(", ")}`);
  push(`- Wording on the page: ${s.note}`);
  push(`- Source line: ${s.source ?? "none (Quran only)"}`, "");
  for (const r of s.refs) push(ayat(r), "");
  if (!s.refs.length) push("> No Quran citation. The claim rests on the hadith named above: **pin the number and the grading.**", "");
  push("Decision: [ ] approve   [ ] request changes   [ ] reject    Note:", "");
}

/* ---------- Lineage ---------- */
const ln = draftLineage();
push("## 2. The line from Adam to Muhammad ﷺ (`content/lineage/lineage.draft.json`)", "");
push(
  "Rules the page keeps: no generation, name, age or date is invented; where the sources give no names or no count the line shows a gap.",
  "Names from Adnan to the Prophet ﷺ follow the classical sira and **must be pinned to a verified edition** (for example Ibn Hisham) before",
  "they can leave draft. Some sources vary on a few names; record each variant here rather than choosing silently.",
  "",
);
const all = [...ln.spine, ...ln.branches.flatMap((b) => b.nodes)];
for (const n of all) {
  const head = n.role === "gap" ? `${n.name} (gap)` : `${n.name}${n.arabic ? ` — ${n.arabic}` : ""}`;
  push(`### ${head}`, "");
  push(`- Role: ${n.role}; link into this entry: ${n.link}; evidence: ${n.evidence.join(", ")}`);
  push(`- Wording on the page: ${n.note}`, "");
  for (const r of n.refs) push(ayat(r), "");
  if (!n.refs.length) push("> No citation. A gap with no citation must say only that it is not established.", "");
  push("Decision: [ ] approve   [ ] request changes   [ ] reject    Note / variant:", "");
}

/* ---------- Placement ---------- */
const tl = draftTimeline();
push("## 3. Era placement of the Complete Timeline (`content/events/placement.draft.json`)", "");
push(
  "An era is an **editorial grouping, not a date**. The order inside an era is not claimed. Parables are never placed. Only the dated milestones carry a",
  "date, labelled exact, traditional or estimate. For each item confirm the era it sits in, or move it to \"Not placed on the line\".",
  "",
);
for (const e of tl.eras) {
  const items = tl.items.filter((i) => i.era === e.k);
  push(`### ${e.title} (${items.length})`, "", `_${e.note}_`, "");
  push("| Item | Track | Date label | Cited ayat |", "|---|---|---|---|");
  for (const i of items) push(`| ${i.title.replace(/\|/g, "/")} | ${i.track} | ${i.date ?? ""} | ${i.refs.slice(0, 4).join("; ")}${i.refs.length > 4 ? "; …" : ""} |`);
  push("");
}

/* ---------- Translations ---------- */
push("## 4. Arabic and Urdu interface strings (`src/lib/i18n/modules/redesign.ts`)", "");
push(
  "Both are drafts written without a qualified translator. Check meaning, register and honorifics (ﷺ after the Prophet, the usual forms for the other",
  "prophets), and that none of them states a date, a count of the Names or a verdict.",
  "",
  "| Key | English | Arabic | Urdu |",
  "|---|---|---|---|",
);
const en = new Map(leaves(redesignStrings("en")));
const ar = new Map(leaves(redesignStrings("ar")));
const ur = new Map(leaves(redesignStrings("ur")));
for (const [k, v] of en) push(`| \`${k}\` | ${v.replace(/\|/g, "/")} | ${(ar.get(k) ?? "").replace(/\|/g, "/")} | ${(ur.get(k) ?? "").replace(/\|/g, "/")} |`);
push("");

const out = join(root, "docs", "review-packs", "redesign-draft-atlas.md");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n") + "\n");
console.log(`review pack: wrote ${out} (${lines.length} lines)`);
