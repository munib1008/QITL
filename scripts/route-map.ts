/**
 * Writes docs/ROUTE_AND_NAVIGATION_MAP.md from the code: every public page route under src/app/[locale], the navigation
 * category it belongs to, whether it is reachable from the Explore registry, and the routes that no registry entry reaches
 * (orphans). Nothing is typed by hand; run it again after adding a route.
 *
 *   npx tsx scripts/route-map.ts          write the document
 *   npx tsx scripts/route-map.ts --check  exit 1 when the document is out of date
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { groupOf } from "../src/lib/nav-groups";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "src", "app", "[locale]");
const out = join(root, "docs", "ROUTE_AND_NAVIGATION_MAP.md");

function walk(dir: string, acc: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (name === "page.tsx") acc.push(p);
  }
  return acc;
}

const routes = walk(appDir)
  .map((p) => "/" + relative(appDir, dirname(p)).split(sep).join("/"))
  .map((r) => (r === "/." ? "/" : r))
  .sort();

/** Hrefs that the navigation registry (src/lib/nav.ts) lists. Read as text so this script needs no i18n runtime. */
const navSrc = readFileSync(join(root, "src", "lib", "nav.ts"), "utf8");
const registry = new Set([...navSrc.matchAll(/href: "(\/[^"]*)"/g)].map((m) => m[1]!));
const headerSrc = readFileSync(join(root, "src", "components", "shell", "SiteHeader.tsx"), "utf8");
for (const m of headerSrc.matchAll(/href: "(\/[^"]*)"/g)) registry.add(m[1]!);
/** Footer links (SiteFooter in the same file) and account pages count as reached by an entry that is not a section. */
const footer = new Set([...headerSrc.matchAll(/<Link href="(\/[^"]*)"/g)].map((m) => m[1]!));
const isFixture = (r: string) => r.endsWith("-fixture");

const isDynamic = (r: string) => r.includes("[");
const parentIn = (r: string): string | null => {
  const parts = r.split("/").filter(Boolean);
  while (parts.length > 1) {
    parts.pop();
    const cand = "/" + parts.join("/");
    if (registry.has(cand)) return cand;
  }
  return null;
};

interface Row {
  route: string;
  group: string;
  how: string;
}
const rows: Row[] = routes.map((r) => {
  const base = r.replace(/\/\[[^\]]+\]/g, "").replace(/\[[^\]]+\]/g, "") || "/";
  const group = groupOf(r) ?? groupOf(base) ?? (parentIn(r) ? (groupOf(parentIn(r)!) ?? "—") : "—");
  const how = registry.has(r) ? "registry" : footer.has(r) ? "footer" : isFixture(r) ? "test fixture" : r === "/sign-in" || r.startsWith("/account") ? "account" : parentIn(r) ? `child of ${parentIn(r)}` : r.startsWith("/admin") ? "admin workspace" : r.startsWith("/mufti") ? "role workspace (muftis)" : r === "/" ? "home" : "not in the registry";
  return { route: r, group: String(group), how };
});

const orphans = rows.filter((r) => r.how === "not in the registry" && !isDynamic(r.route) && r.route !== "/offline");
const lines: string[] = [];
lines.push("# Route and navigation map", "", "Generated by `npx tsx scripts/route-map.ts` from `src/app/[locale]` and `src/lib/nav.ts`. Do not edit by hand.", "");
lines.push(`${rows.length} page routes. ${rows.filter((r) => r.how === "registry").length} are listed in the navigation registry or the header; ${orphans.length} static routes are reached by no registry entry (see "Not in the registry").`, "");
lines.push("| Route | Category | Reached through |", "|---|---|---|");
for (const r of rows) lines.push(`| \`${r.route}\` | ${r.group} | ${r.how} |`);
lines.push("", "## Not in the registry", "", "Static public routes no navigation entry or parent registry route reaches. Each is either reached by an in-page link, a footer link or a deep link, or it is an orphan to fix.", "");
for (const o of orphans) lines.push(`- \`${o.route}\``);
lines.push("");
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  const same = existsSync(out) && readFileSync(out, "utf8") === text;
  console.log(same ? "route map is up to date" : "route map is out of date: run npx tsx scripts/route-map.ts");
  process.exit(same ? 0 : 1);
}
writeFileSync(out, text);
console.log(`wrote ${relative(root, out)}: ${rows.length} routes, ${orphans.length} not in the registry`);
