/**
 * The inventory migration is generated from content/events/inventory.draft.json (`pnpm tsx scripts/gen-event-inventory.ts`),
 * so the reviewed list and the database seed cannot drift: tests/unit/events.test.ts regenerates it and compares.
 * Draft shells only: title, track, category and verse ranges. No claims, no dates, no summaries.
 */
import { parseRef } from "./verify";

export interface InventoryItem {
  slug: string;
  title: string;
  track: "prophets" | "people" | "communities" | "events" | "parables" | "seerah";
  category: "sacred_history" | "prophetic_life";
  name_source: "quran" | "later_tradition";
  refs: string[];
}
export interface Inventory {
  status: "draft";
  note: string;
  items: InventoryItem[];
}

/** Verse references added after the base migration was applied (content/events/inventory-additions.json). */
export interface InventoryAdditions {
  migration: string;
  note: string;
  added: Array<{ slug: string; refs: string[] }>;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function inventorySql(inv: Inventory): string {
  const rows = inv.items.map((i) => `  (${q(i.slug)}, ${q(i.title)}, ${q(i.track)}, ${q(i.category)}, ${q(i.name_source)})`);
  const refs: string[] = [];
  for (const i of inv.items) {
    i.refs.forEach((r, n) => {
      const p = parseRef(r);
      if (!p) throw new Error(`bad reference ${r} in ${i.slug}`);
      refs.push(`  (${q(i.slug)}, ${p.surah}, ${p.from}, ${p.to}, ${n})`);
    });
  }
  return `set search_path = public, extensions;

-- GENERATED by scripts/gen-event-inventory.ts from content/events/inventory.draft.json. Do not edit by hand.
-- The Event Universe inventory: ${inv.items.length} DRAFT shells (title, track, verified verse ranges, nothing else).
-- Each reference was checked against the imported Quran text (tests/unit/events.test.ts). Every row is status 'draft':
-- nothing here is public, dated or ordered. Ordering is "unassigned" (the "Order not established" lane) until a reviewer
-- adds a cited ordering claim. Names flagged later_tradition are not in the Quranic passage.

insert into public.historical_events (slug, title, track, category, name_source, date_precision, ordering_kind, status)
select v.slug, v.title, v.track, v.category, v.name_source, 'unknown', 'unassigned', 'draft'
from (values
${rows.join(",\n")}
) as v(slug, title, track, category, name_source);

insert into public.event_verse_refs (event_id, surah, ayah_from, ayah_to, position)
select e.id, v.surah, v.ayah_from, v.ayah_to, v.position
from (values
${refs.join(",\n")}
) as v(slug, surah, ayah_from, ayah_to, position)
join public.historical_events e on e.slug = v.slug;
`;
}

/**
 * The inventory as the (frozen, already applied) base migration 20261031002451 knows it: the file without the references
 * that were added later. The added references are always the LAST ones of their item, so the positions agree.
 */
export function baseInventory(inv: Inventory, additions: InventoryAdditions): Inventory {
  const drop = new Map(additions.added.map((a) => [a.slug, new Set(a.refs)]));
  return { ...inv, items: inv.items.map((i) => ({ ...i, refs: drop.has(i.slug) ? i.refs.filter((r) => !drop.get(i.slug)!.has(r)) : i.refs })) };
}

/**
 * The additive migration: only the new event_verse_refs rows, joined to the existing event by slug, positions continuing
 * after the base ones, idempotent (a row that is already there is left alone). It creates no event and changes no row.
 */
export function additionsSql(inv: Inventory, additions: InventoryAdditions): string {
  const rows: string[] = [];
  for (const a of additions.added) {
    const item = inv.items.find((i) => i.slug === a.slug);
    if (!item) throw new Error(`addition for unknown item ${a.slug}`);
    for (const r of a.refs) {
      const p = parseRef(r);
      if (!p) throw new Error(`bad reference ${r} in ${a.slug}`);
      rows.push(`  (${q(a.slug)}, ${p.surah}, ${p.from}, ${p.to}, ${item.refs.indexOf(r)})`);
    }
  }
  return `set search_path = public, extensions;

-- GENERATED by scripts/gen-event-inventory.ts from content/events/inventory-additions.json and inventory.draft.json. Do not edit by hand.
-- Additive: ${rows.length} verse references added to existing inventory items after migration 20261031002451 was applied
-- (that migration is frozen). It inserts event_verse_refs rows only; no event is created, changed or published, and no claim is touched.
-- Idempotent: on conflict (event, range) do nothing, so running it twice changes nothing. (A published event's references are
-- fixed by the database; every inventory item is a draft, so none is affected.)
-- Each range exists in the imported Quran text and has an anchor word in tests/fixtures/event-anchors.json.

insert into public.event_verse_refs (event_id, surah, ayah_from, ayah_to, position)
select e.id, v.surah, v.ayah_from, v.ayah_to, v.position
from (values
${rows.join(",\n")}
) as v(slug, surah, ayah_from, ayah_to, position)
join public.historical_events e on e.slug = v.slug
on conflict (event_id, surah, ayah_from, ayah_to) do nothing;
`;
}
